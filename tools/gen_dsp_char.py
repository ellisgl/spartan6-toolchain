#!/usr/bin/env python3
"""Generate DSP48A1 characterization designs for the delay model.

    python3 tools/gen_dsp_char.py     # writes tests/dsp_char0 .. dsp_char29

Every combination of the seven pipeline-register groups (A, B, C, D, M, P,
OPMODE: 128) appears once with OPMODE driven from logic (dsp_char0..7), and
the 64 combinations of A..P once for each common constant OPMODE in
CONST_OPMODES (dsp_char8..), 16 DSPs per design (the xc6slx9 has 16). ISE
times a constant OPMODE differently (it drops the paths the mode can't
use). Inputs
come from a shift register fed by a pin and P is XOR-reduced into a
flip-flop, so every DSP input and P are on timed paths. (ISE doesn't allow M
and P to be used together; M gets P's timing.) These designs are only for
`make timing-data` (ISE's timing simulation SDF); they don't do anything
useful on the board.
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GROUPS = ["A", "B", "C", "D", "M", "P", "O"]  # O = OPMODEREG
PER_DESIGN = 16
# X = M (multiplier), Z = 0 / P / C, with and without the pre-adder, and
# X = D:A:B. Which modes yosys's DSP48A1 mapping produces: 01 (multiply),
# 09 (multiply-accumulate), 0d (multiply-add C).
CONST_OPMODES = [0x01, 0x09, 0x0D, 0x11, 0x1D, 0x03]


def params(cfg):
    """cfg: bits 0..6 = A B C D M P OPMODE registered, bit 8.. = constant
    OPMODE + 1 (0: OPMODE from logic)."""
    a, b, c, d, m, p, o = (cfg >> i & 1 for i in range(7))
    return {
        "A0REG": 0, "A1REG": a, "B0REG": 0, "B1REG": b, "CREG": c, "DREG": d,
        "MREG": m, "PREG": p, "OPMODEREG": o, "CARRYINREG": 0, "CARRYOUTREG": 0,
        "CARRYINSEL": '"OPMODE5"', "RSTTYPE": '"SYNC"',
    }


def design(n, cfgs):
    width = 18 + 18 + 48 + 18 + 8  # A, B, C, D, OPMODE bits per DSP
    lines = [
        f"// DSP48A1 characterization design {n} (generated by tools/gen_dsp_char.py).",
        f"module dsp_char{n} (input wire clk, input wire din, output reg dout = 0);",
        f"    reg [{width * len(cfgs) - 1}:0] sr = 0;",
        "    always @(posedge clk) sr <= {sr, din};",
        "    // An XOR between the shift register and the DSP inputs keeps yosys",
        "    // from absorbing the flip-flops into the DSP's input registers",
        "    // (which would change the configuration under test).",
        f"    wire [{width * len(cfgs) - 1}:0] x = sr ^ {{sr[0], sr[{width * len(cfgs) - 1}:1]}};",
        f"    wire [{len(cfgs) - 1}:0] red;",
    ]
    for i, cfg in enumerate(cfgs):
        base = i * width
        op = None if cfg >> 8 == 0 else (cfg >> 8) - 1
        ps = ", ".join(f".{k}({v})" for k, v in params(cfg & 0x7f).items())
        opmode = f"x[{base + 109}:{base + 102}]" if op is None else f"8'h{op:02x}"
        lines += [
            f"    // {''.join(g for j, g in enumerate(GROUPS) if cfg >> j & 1) or 'none'} registered, "
            f"OPMODE {'from logic' if op is None else f'{op:#04x}'}",
            f"    wire [47:0] p{i};",
            f"    DSP48A1 #({ps}) dsp{i} (",
            f"        .CLK(clk),",
            f"        .A(x[{base + 17}:{base}]), .B(x[{base + 35}:{base + 18}]),",
            f"        .C(x[{base + 83}:{base + 36}]), .D(x[{base + 101}:{base + 84}]),",
            f"        .OPMODE({opmode}),",
            "        .CEA(1'b1), .CEB(1'b1), .CEC(1'b1), .CED(1'b1), .CEM(1'b1), .CEP(1'b1),",
            "        .CEOPMODE(1'b1), .CECARRYIN(1'b1),",
            "        .RSTA(1'b0), .RSTB(1'b0), .RSTC(1'b0), .RSTD(1'b0), .RSTM(1'b0), .RSTP(1'b0),",
            "        .RSTOPMODE(1'b0), .RSTCARRYIN(1'b0), .CARRYIN(1'b0),",
            f"        .P(p{i})",
            "    );",
            f"    assign red[{i}] = ^p{i};",
        ]
    lines += ["    always @(posedge clk) dout <= ^red;", "endmodule", ""]
    return "\n".join(lines)


def main():
    cfgs = list(range(1 << len(GROUPS)))
    # Constant OPMODE: OPMODEREG doesn't matter, so the 64 others.
    # (Accumulating, Z = P, needs PREG: ISE rejects it otherwise.)
    cfgs += [(op + 1) << 8 | c for op in CONST_OPMODES for c in range(1 << (len(GROUPS) - 1))
             if not (op >> 2 & 3 == 2 and not c >> 5 & 1)]
    for n in range(len(cfgs) // PER_DESIGN):
        d = os.path.join(ROOT, "tests", f"dsp_char{n}")
        os.makedirs(d, exist_ok=True)
        write(os.path.join(d, f"dsp_char{n}.v"), design(n, cfgs[n * PER_DESIGN:(n + 1) * PER_DESIGN]))
        write(os.path.join(d, "pins.ucf"),
              'NET "clk"  LOC = P56  | IOSTANDARD = LVTTL;\n'
              'NET "din"  LOC = P55  | IOSTANDARD = LVTTL;\n'
              'NET "dout" LOC = P134 | IOSTANDARD = LVTTL;\n')
    print(f"wrote tests/dsp_char0 .. dsp_char{len(cfgs) // PER_DESIGN - 1}")


def write(path, text):
    """Only when changed, so make doesn't rebuild what's already measured."""
    if os.path.exists(path) and open(path).read() == text:
        return
    with open(path, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
