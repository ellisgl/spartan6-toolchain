#!/usr/bin/env python3
"""Generate DSP48A1 characterization designs for the delay model.

    python3 tools/gen_dsp_char.py     # writes tests/dsp_char0 .. dsp_char29
                                      # and tests/dsp_casc_char0 .. 15

Every combination of the seven pipeline-register groups (A, B, C, D, M, P,
OPMODE: 128) appears once with OPMODE driven from logic (dsp_char0..7), and
the 64 combinations of A..P once for each common constant OPMODE in
CONST_OPMODES (dsp_char8..), 16 DSPs per design (the xc6slx9 has 16). ISE
times a constant OPMODE differently (it drops the paths the mode can't
use). Inputs
come from a shift register fed by a pin and P is XOR-reduced into a
flip-flop, so every DSP input and P are on timed paths. (ISE doesn't allow M
and P to be used together; M gets P's timing.) These designs are only for
`make timing-data` (ISE's timing simulation SDF); they don't do anything
useful on the board.

dsp_casc_char*: the cascade arcs (PCIN, BCIN, CARRYIN in; PCOUT, BCOUT,
CARRYOUT out), one chain of all 16 DSPs per design, each DSP fed by the one
below through PCOUT -> PCIN, BCOUT -> B and CARRYOUT -> CARRYIN. The 128
OPMODE-from-logic configurations appear twice, rotated by half a chain, so
every configuration is measured both driving and receiving a cascade, and
the 64 A..P configurations again for each of CASC_CONST_OPMODES.
CARRYOUTF joins P in the XOR-reduce.
"""

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GROUPS = ["A", "B", "C", "D", "M", "P", "O"]  # O = OPMODEREG
PER_DESIGN = 16
# X = M (multiplier), Z = 0 / P / C, with and without the pre-adder, and
# X = D:A:B. Which modes yosys's DSP48A1 mapping produces: 01 (multiply),
# 09 (multiply-accumulate), 0d (multiply-add C).
# 51: the pre-subtracter. Then modes for hand-instantiated DSPs (appended,
# so the designs above keep their numbers): 0b P + D:A:B, 0c C, 0f C + D:A:B
# (48-bit add), 19 pre-adder multiply-accumulate, 89 P - M and 8d C - M
# (post-subtract).
CONST_OPMODES = [0x01, 0x09, 0x0D, 0x11, 0x1D, 0x03, 0x51, 0x0B, 0x0C, 0x0F, 0x19, 0x89, 0x8D]
# Constant OPMODEs measured in cascade chains (dsp_casc_char*): 05 is
# multiply plus PCIN, what yosys uses for P cascades; 07 D:A:B + PCIN and
# 15 pre-adder multiply plus PCIN.
CASC_CONST_OPMODES = [0x05, 0x07, 0x15]


def params(cfg):
    """cfg: bits 0..6 = A B C D M P OPMODE registered, bit 8.. = constant
    OPMODE + 1 (0: OPMODE from logic)."""
    a, b, c, d, m, p, o = (cfg >> i & 1 for i in range(7))
    return {
        "A0REG": 0, "A1REG": a, "B0REG": 0, "B1REG": b, "CREG": c, "DREG": d,
        "MREG": m, "PREG": p, "OPMODEREG": o, "CARRYINREG": 0, "CARRYOUTREG": 0,
        "CARRYINSEL": '"OPMODE5"', "RSTTYPE": '"SYNC"',
    }


def design(n, cfgs):
    width = 18 + 18 + 48 + 18 + 8  # A, B, C, D, OPMODE bits per DSP
    lines = [
        f"// DSP48A1 characterization design {n} (generated by tools/gen_dsp_char.py).",
        f"module dsp_char{n} (input wire clk, input wire din, output reg dout = 0);",
        f"    reg [{width * len(cfgs) - 1}:0] sr = 0;",
        "    always @(posedge clk) sr <= {sr, din};",
        "    // An XOR between the shift register and the DSP inputs keeps yosys",
        "    // from absorbing the flip-flops into the DSP's input registers",
        "    // (which would change the configuration under test).",
        f"    wire [{width * len(cfgs) - 1}:0] x = sr ^ {{sr[0], sr[{width * len(cfgs) - 1}:1]}};",
        f"    wire [{len(cfgs) - 1}:0] red;",
    ]
    for i, cfg in enumerate(cfgs):
        base = i * width
        op = None if cfg >> 8 == 0 else (cfg >> 8) - 1
        ps = ", ".join(f".{k}({v})" for k, v in params(cfg & 0x7f).items())
        opmode = f"x[{base + 109}:{base + 102}]" if op is None else f"8'h{op:02x}"
        lines += [
            f"    // {''.join(g for j, g in enumerate(GROUPS) if cfg >> j & 1) or 'none'} registered, "
            f"OPMODE {'from logic' if op is None else f'{op:#04x}'}",
            f"    wire [47:0] p{i};",
            f"    DSP48A1 #({ps}) dsp{i} (",
            f"        .CLK(clk),",
            f"        .A(x[{base + 17}:{base}]), .B(x[{base + 35}:{base + 18}]),",
            f"        .C(x[{base + 83}:{base + 36}]), .D(x[{base + 101}:{base + 84}]),",
            f"        .OPMODE({opmode}),",
            "        .CEA(1'b1), .CEB(1'b1), .CEC(1'b1), .CED(1'b1), .CEM(1'b1), .CEP(1'b1),",
            "        .CEOPMODE(1'b1), .CECARRYIN(1'b1),",
            "        .RSTA(1'b0), .RSTB(1'b0), .RSTC(1'b0), .RSTD(1'b0), .RSTM(1'b0), .RSTP(1'b0),",
            "        .RSTOPMODE(1'b0), .RSTCARRYIN(1'b0), .CARRYIN(1'b0),",
            f"        .P(p{i})",
            "    );",
            f"    assign red[{i}] = ^p{i};",
        ]
    lines += ["    always @(posedge clk) dout <= ^red;", "endmodule", ""]
    return "\n".join(lines)


def casc_design(n, cfgs):
    width = 18 + 18 + 48 + 18 + 8  # as design(); B is only used by the bottom DSP
    name = f"dsp_casc_char{n}"
    lines = [
        f"// DSP48A1 cascade characterization design {n} (generated by tools/gen_dsp_char.py).",
        f"module {name} (input wire clk, input wire din, output reg dout = 0);",
        f"    reg [{width * len(cfgs) - 1}:0] sr = 0;",
        "    always @(posedge clk) sr <= {sr, din};",
        f"    wire [{width * len(cfgs) - 1}:0] x = sr ^ {{sr[0], sr[{width * len(cfgs) - 1}:1]}};",
        f"    wire [{len(cfgs) - 1}:0] red;",
    ]
    for i, cfg in enumerate(cfgs):
        base = i * width
        op = None if cfg >> 8 == 0 else (cfg >> 8) - 1
        prm = params(cfg & 0x7f)
        if i > 0:
            prm["CARRYINSEL"] = '"CARRYIN"'
        ps = ", ".join(f".{k}({v})" for k, v in prm.items())
        b = f"x[{base + 35}:{base + 18}]" if i == 0 else f"bc{i - 1}"
        pcin = "48'd0" if i == 0 else f"pc{i - 1}"
        cin = "1'b0" if i == 0 else f"co{i - 1}"
        last = i == len(cfgs) - 1
        lines += [
            f"    // {''.join(g for j, g in enumerate(GROUPS) if cfg >> j & 1) or 'none'} registered"
            + ("" if op is None else f", OPMODE {op:#04x}"),
            f"    wire [47:0] p{i}, pc{i};",
            f"    wire [17:0] bc{i};",
            f"    wire co{i}, cof{i};",
            f"    DSP48A1 #({ps}) dsp{i} (",
            f"        .CLK(clk),",
            f"        .A(x[{base + 17}:{base}]), .B({b}),",
            f"        .C(x[{base + 83}:{base + 36}]), .D(x[{base + 101}:{base + 84}]),",
            f"        .OPMODE({f'x[{base + 109}:{base + 102}]' if op is None else f"8'h{op:02x}"}),",
            "        .CEA(1'b1), .CEB(1'b1), .CEC(1'b1), .CED(1'b1), .CEM(1'b1), .CEP(1'b1),",
            "        .CEOPMODE(1'b1), .CECARRYIN(1'b1),",
            "        .RSTA(1'b0), .RSTB(1'b0), .RSTC(1'b0), .RSTD(1'b0), .RSTM(1'b0), .RSTP(1'b0),",
            f"        .RSTOPMODE(1'b0), .RSTCARRYIN(1'b0), .CARRYIN({cin}), .PCIN({pcin}),",
            f"        .P(p{i}), .CARRYOUTF(cof{i}),",
            f"        .PCOUT({'' if last else f'pc{i}'}), .BCOUT({'' if last else f'bc{i}'}), "
            f".CARRYOUT({'' if last else f'co{i}'})",
            "    );",
            f"    assign red[{i}] = ^p{i} ^ cof{i};",
        ]
    lines += ["    always @(posedge clk) dout <= ^red;", "endmodule", ""]
    return name, "\n".join(lines)


def main():
    cfgs = list(range(1 << len(GROUPS)))
    # Constant OPMODE: OPMODEREG doesn't matter, so the 64 others.
    # (Accumulating, Z = P, needs PREG: ISE rejects it otherwise.)
    cfgs += [(op + 1) << 8 | c for op in CONST_OPMODES for c in range(1 << (len(GROUPS) - 1))
             if not (op >> 2 & 3 == 2 and not c >> 5 & 1)]
    for n in range(len(cfgs) // PER_DESIGN):
        d = os.path.join(ROOT, "tests", f"dsp_char{n}")
        os.makedirs(d, exist_ok=True)
        write(os.path.join(d, f"dsp_char{n}.v"), design(n, cfgs[n * PER_DESIGN:(n + 1) * PER_DESIGN]))
        write(os.path.join(d, "pins.ucf"),
              'NET "clk"  LOC = P56  | IOSTANDARD = LVTTL;\n'
              'NET "din"  LOC = P55  | IOSTANDARD = LVTTL;\n'
              'NET "dout" LOC = P134 | IOSTANDARD = LVTTL;\n')
    print(f"wrote tests/dsp_char0 .. dsp_char{len(cfgs) // PER_DESIGN - 1}")
    # Cascades: OPMODE from logic only (constant-OPMODE variants take their
    # cascade arcs from these; see s6-chipdb).
    logic = list(range(1 << len(GROUPS)))
    half = PER_DESIGN // 2
    chains = [logic[i:i + PER_DESIGN] for i in range(0, len(logic), PER_DESIGN)]
    chains += [c[half:] + c[:half] for c in chains]
    # Constant OPMODEs (OPMODEREG doesn't matter: the 64 A..P configurations),
    # 15 to a chain above a feeder DSP with OPMODE from logic (ISE's DRC: a
    # DSP using PCIN needs one below it).
    for op in CASC_CONST_OPMODES:
        const = [(op + 1) << 8 | c for c in range(1 << (len(GROUPS) - 1))]
        n = PER_DESIGN - 1
        cc = [const[i:i + n] for i in range(0, len(const), n)]
        chains += [[0] + c for c in cc] + [[0] + c[len(c) // 2:] + c[:len(c) // 2] for c in cc]
    for n, cfgs in enumerate(chains):
        name, text = casc_design(n, cfgs)
        d = os.path.join(ROOT, "tests", name)
        os.makedirs(d, exist_ok=True)
        write(os.path.join(d, f"{name}.v"), text)
        write(os.path.join(d, "pins.ucf"),
              'NET "clk"  LOC = P56  | IOSTANDARD = LVTTL;\n'
              'NET "din"  LOC = P55  | IOSTANDARD = LVTTL;\n'
              'NET "dout" LOC = P134 | IOSTANDARD = LVTTL;\n')
    print(f"wrote tests/dsp_casc_char0 .. dsp_casc_char{len(chains) - 1}")


def write(path, text):
    """Only when changed, so make doesn't rebuild what's already measured."""
    if os.path.exists(path) and open(path).read() == text:
        return
    with open(path, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
