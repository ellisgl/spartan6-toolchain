"""ROM contents for tests/rom: 256 bytes from a 16-bit xorshift generator.
Shared by the Verilog generator (python3 tools/rom_data.py > ...) and
tools/rom-test.py."""


def rom_bytes():
    x = 0xACE1
    out = []
    for _ in range(256):
        x ^= (x << 7) & 0xFFFF
        x ^= x >> 9
        x ^= (x << 8) & 0xFFFF
        out.append((x ^ (x >> 8)) & 0xFF)
    return out


def rom7_bytes():
    """128-entry table (7-input functions: MUXF7 without MUXF8)."""
    return rom_bytes()[1::2]


def module(name, bits, data):
    print(f"module {name} (input wire [{bits - 1}:0] addr, output reg [7:0] data);")
    print("    always @(*)")
    print("        case (addr)")
    for a, d in enumerate(data):
        print(f"            {bits}'d{a}: data = 8'h{d:02x};")
    print("        endcase")
    print("endmodule")


if __name__ == "__main__":
    print("// Generated by tools/rom_data.py; do not edit.")
    module("rom_table", 8, rom_bytes())
    module("rom_table7", 7, rom7_bytes())
