"""Initial contents for tests/bram's memories, shared by the Verilog
generator (python3 tools/bram_data.py) and tools/bram-test.py."""

MEMS = [  # (name, depth, width)
    ("m0", 2048, 8),
    ("m1", 512, 32),
    ("m2", 1024, 8),
]


def init(index, depth, width):
    x = 0x12345678 ^ (index * 0x9E3779B9) & 0xFFFFFFFF
    out = []
    for _ in range(depth):
        x ^= (x << 13) & 0xFFFFFFFF
        x ^= x >> 17
        x ^= (x << 5) & 0xFFFFFFFF
        out.append(x & ((1 << width) - 1))
    return out


if __name__ == "__main__":
    print("// Generated by tools/bram_data.py; do not edit.")
    for i, (name, depth, width) in enumerate(MEMS):
        print(f"initial begin")
        for a, v in enumerate(init(i, depth, width)):
            print(f"    {name}[{a}] = {width}'h{v:0{width // 4}x};")
        print("end")
